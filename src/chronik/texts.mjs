// Rufstufen 1..8 (Hasserfüllt ... Ehrfürchtig)
export const STANDINGS = {
  de: ["Hasserfüllt", "Feindselig", "Unfreundlich", "Neutral", "Freundlich", "Wohlwollend", "Respektvoll", "Ehrfürchtig"],
  en: ["Hated", "Hostile", "Unfriendly", "Neutral", "Friendly", "Honored", "Revered", "Exalted"],
};

function fill(v, args) {
  return v.replace(/\{(\d+)\}/g, (m, i) => (args[Number(i)] === undefined || args[Number(i)] === null ? "" : String(args[Number(i)])));
}

// Text nach Schlüssel: erst die Chronik-Texte der Sprache, dann die Medaillen-Texte, dann Deutsch; unbekannt -> der Schlüssel
export function ct(lang, key, ...args) {
  const l = normLang(lang);
  for (const table of [CHRONIK_TEXTS[l], MEDAL_TEXTS[l], CHRONIK_TEXTS.de, MEDAL_TEXTS.de]) {
    if (Object.hasOwn(table, key) && typeof table[key] === "string") return fill(table[key], args);
  }
  return String(key);
}

export function hasCt(lang, key) {
  const l = normLang(lang);
  return [CHRONIK_TEXTS[l], MEDAL_TEXTS[l]].some((t) => Object.hasOwn(t, key) && typeof t[key] === "string");
}

// "eins"/"mehrere": Schlüssel <base>_one bei 1, sonst <base>_other
export function ctn(lang, base, n, ...args) {
  return ct(lang, base + (n === 1 ? "_one" : "_other"), n, ...args);
}

export function difficultyName(lang, id) {
  const t = DIFFICULTY[normLang(lang)];
  return id !== null && id !== undefined && Object.hasOwn(t, String(id)) ? t[String(id)] : null;
}

export function standingName(lang, n) {
  return STANDINGS[normLang(lang)][n - 1] || String(n);
}
