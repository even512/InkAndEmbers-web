export function st(lang, key, ...args) {
  const l = normLang(lang);
  const v = SHARE_TEXTS[l][key] ?? SHARE_TEXTS.de[key];
  if (typeof v !== "string") return t(l, key, ...args);
  return v.replace(/\{(\d+)\}/g, (m, i) => (args[Number(i)] === undefined || args[Number(i)] === null ? "" : String(args[Number(i)])));
}
